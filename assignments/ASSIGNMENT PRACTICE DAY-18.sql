-- Q10. Customer Wallet Deduction

DELIMITER //
CREATE TRIGGER TRG_BEFORE_INSERT_WALLET_PAYMENT
BEFORE INSERT ON PAYMENTS
FOR EACH ROW
BEGIN
DECLARE V_WALLET_BALANCE DECIMAL(10,2);
DECLARE V_CUSTOMER_ID INT;
IF NEW.PAYMENT_METHOD = 'WALLET'
AND NEW.PAYMENT_STATUS = 'SUCCESS' THEN
SELECT CUSTOMER_ID
INTO V_CUSTOMER_ID
FROM ORDERS
WHERE ORDER_ID = NEW.ORDER_ID;
SELECT WALLET_BALANCE
INTO V_WALLET_BALANCE
FROM CUSTOMERS
WHERE CUSTOMER_ID = V_CUSTOMER_ID;
IF V_WALLET_BALANCE < NEW.PAYMENT_AMOUNT THEN
SIGNAL SQLSTATE '45000'
SET MESSAGE_TEXT = 'Insufficient wallet balance.';
END IF;
END IF;
END //
DELIMITER ; 

