-- Q22. Restore Product Stock


DELIMITER //
CREATE TRIGGER TRG_AFTER_DELETE_ORDER_ITEM
AFTER DELETE ON ORDER_ITEMS
FOR EACH ROW
BEGIN
UPDATE PRODUCTS
SET STOCK_QUANTITY = STOCK_QUANTITY + OLD.QUANTITY
WHERE PRODUCT_ID = OLD.PRODUCT_ID;
INSERT INTO STOCK_HISTORY(PRODUCT_ID, OLD_STOCK, NEW_STOCK,CHANGE_TYPE, CHANGED_AT)
SELECT
	    OLD.PRODUCT_ID,
        OLD_STOCK,
        NEW_STOCK,
        'RETURN',
        NOW()
    FROM (SELECT
		  STOCK_QUANTITY - OLD.QUANTITY AS OLD_STOCK,
            STOCK_QUANTITY AS NEW_STOCK
        FROM PRODUCTS
        WHERE PRODUCT_ID = OLD.PRODUCT_ID
    ) AS STOCK_DATA;
END //
DELIMITER ;
